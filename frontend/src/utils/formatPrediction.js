/**
 * TerraSpectra — formatPrediction Utility
 *
 * Week 3 Day 4 Deliverable
 *
 * Formats model scores, uncertainty metrics, and metadata values with strict
 * adherence to ML team definitions and integration guardrails:
 *   • Never automatically conflates numeric scores with calibrated confidence or disease infection probability.
 *   • Explicitly labels score semantics: Softmax Score, Calibrated Confidence, or Raw Model Logit.
 *   • Clearly distinguishes unavailable values (null / undefined) from zero or negative results.
 *   • Identifies and labels provenance: Real Model Prediction, Test Fixture, or Local Mock.
 */

import {
  SCORE_TYPES,
  SCORE_TYPE_LABELS,
} from "../types/prediction.js";

/**
 * Format a numeric model prediction score with explicit semantic definitions.
 *
 * @param {number|null|undefined} score
 * @param {string} [scoreType=SCORE_TYPES.SOFTMAX_SCORE]
 * @returns {{ formatted: string, label: string, isAvailable: boolean, type: string }}
 */
export function formatModelScore(score, scoreType = SCORE_TYPES.SOFTMAX_SCORE) {
  const isAvailable = typeof score === "number" && !Number.isNaN(score);
  const typeKey = scoreType || SCORE_TYPES.SOFTMAX_SCORE;
  const label = SCORE_TYPE_LABELS[typeKey] || "Model Score";

  if (!isAvailable) {
    return {
      formatted: "Unavailable",
      label,
      isAvailable: false,
      type: typeKey,
    };
  }

  // Handle raw logit numbers differently from normalized probabilities
  if (typeKey === SCORE_TYPES.RAW_LOGIT) {
    return {
      formatted: score.toFixed(3),
      label,
      isAvailable: true,
      type: typeKey,
    };
  }

  // Normal percentage formatting for softmax / calibrated confidence (0.0 to 1.0)
  const percentage = (score * 100).toFixed(1);
  return {
    formatted: `${percentage}%`,
    label,
    isAvailable: true,
    type: typeKey,
  };
}

/**
 * Format uncertainty metric (variance or entropy).
 *
 * @param {number|null|undefined} uncertainty
 * @returns {string} Formatted uncertainty string or explicit unavailable label
 */
export function formatUncertainty(uncertainty) {
  if (typeof uncertainty !== "number" || Number.isNaN(uncertainty)) {
    return "Not estimated";
  }
  return `± ${(uncertainty * 100).toFixed(1)}%`;
}

/**
 * Format spatial ground sampling distance (GSD) in meters.
 *
 * @param {number|null|undefined} resolutionM
 * @returns {string}
 */
export function formatResolution(resolutionM) {
  if (typeof resolutionM !== "number" || Number.isNaN(resolutionM) || resolutionM <= 0) {
    return "Pending scene intake";
  }
  return `${resolutionM.toFixed(1)}m / px`;
}

/**
 * Determine data provenance and appropriate visual badge.
 *
 * @param {object} [featureOrMetadata]
 * @param {boolean} [isDemoContext=false]
 * @returns {{ type: "real"|"fixture"|"mock", label: string, badgeClass: string, description: string }}
 */
export function getProvenanceInfo(featureOrMetadata = {}, isDemoContext = false) {
  const meta = featureOrMetadata?.metadata || featureOrMetadata || {};
  const isFixture = Boolean(
    featureOrMetadata?._isSampleFixture || meta._isSampleFixture
  );
  const isMock = Boolean(
    featureOrMetadata?._isMock ||
      meta.is_mock ||
      meta.isMock ||
      isDemoContext
  );

  if (isFixture) {
    return {
      type: "fixture",
      label: "Sample Test Fixture",
      badgeClass: "badge-fixture",
      description: "Pre-recorded test sample used for UI and integration testing.",
    };
  }

  if (isMock) {
    return {
      type: "mock",
      label: "Simulated Mock Data",
      badgeClass: "badge-mock",
      description: "Generated by local fallback adapter. Not verified agronomic data.",
    };
  }

  return {
    type: "real",
    label: "Live Model Output",
    badgeClass: "badge-real",
    description: "Inferred from active machine learning model checkpoint.",
  };
}

/**
 * Safely format generic metadata values while preserving zeroes and booleans.
 *
 * @param {*} value
 * @param {string} [fallback="Not provided"]
 * @returns {string}
 */
export function formatFieldValue(value, fallback = "Not provided") {
  if (value === null || value === undefined || value === "") {
    return fallback;
  }
  return String(value);
}

export default {
  formatModelScore,
  formatUncertainty,
  formatResolution,
  getProvenanceInfo,
  formatFieldValue,
};
